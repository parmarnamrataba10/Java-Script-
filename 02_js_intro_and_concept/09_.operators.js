console.log("Equal:", 9 == "9"); 
console.log("Strict Equal:", 9 === "9"); 
console.log("Not Equal:", 10 != 3); 
console.log("Greater Than:", 5 > 5); 
console.log("Less Than:", 2 < 6); 


             // 4. Logical Operators //


