
// Arrow Function: A shorter and modern way to write functions .

// It is uses like => (arrow) syntax.

function normalFunction() {
  console.log("normal function");
}

// Function invocation
normalFunction();


// this the way to use arrow function //


// Arrow function
const arrowFunction = () => {
  console.log("arrow function");
};
// Arrow function invocation
arrowFunction();


// if there is only one line code we can omit the {} braces //

const arrowFunction2 = () => console.log(" arrowfunction can be used like this also");

arrowFunction2();


